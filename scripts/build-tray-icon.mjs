/**
 * Generates the macOS menu-bar mark: resources/trayTemplate.svg plus the PNGs the Tray needs.
 *
 * Run: node scripts/build-tray-icon.mjs
 *
 * Why a hand-rolled rasteriser rather than an SVG library:
 * a Tray must be handed a NativeImage and nativeImage cannot read SVG, so the vector has to be
 * baked to PNG somewhere. Every option available here failed or wasn't worth the cost —
 * qlmanage renders this stroke-only artwork blank, no rsvg/ImageMagick/cairosvg is installed,
 * and Chromium-via-Electron stalls capturing a hidden transparent window. Adding sharp or
 * node-canvas for two 18px icons is a heavy dependency for the repo. The mark is pure geometry
 * (segments, circles), so exact coverage is a few lines of distance maths and the output is
 * deterministic and dependency-free.
 *
 * Output follows Apple's template-image convention:
 *   trayTemplate.png     18x18
 *   trayTemplate@2x.png  36x36
 * The "Template" suffix is what makes AppKit tint the artwork itself — black on a light menu
 * bar, white on a dark one — so these are pure black with an alpha channel and carry no colour.
 */
import { deflateSync } from 'node:zlib'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

// ---------------------------------------------------------------- geometry (single source)

/** Design canvas, in the 18pt units macOS uses for menu-bar icons. */
const SIZE = 18
const CX = 9
const CY = 9
const STROKE = 1.25

const R_HEPTAGON = 7.4
const R_RIM = 4.9
const R_HUB = 1.5
const SPOKE_INNER = 2.0
const SPOKE_OUTER = 4.9
const SPOKES = 7

/** Vertex on a circle, rotated so one point faces up. */
function vertex(radius, index, count) {
  const a = ((index / count) * 360 - 90) * (Math.PI / 180)
  return [CX + radius * Math.cos(a), CY + radius * Math.sin(a)]
}

const heptagon = Array.from({ length: 7 }, (_, i) => vertex(R_HEPTAGON, i, 7))
const spokes = Array.from({ length: SPOKES }, (_, i) => [
  vertex(SPOKE_INNER, i, SPOKES),
  vertex(SPOKE_OUTER, i, SPOKES)
])
/** Heptagon drawn as its closing edges, so the rasteriser only needs segment maths. */
const edges = heptagon.map((p, i) => [p, heptagon[(i + 1) % 7]])

// ---------------------------------------------------------------- svg

const path = heptagon.map(([x, y], i) => `${i ? 'L' : 'M'}${x.toFixed(2)} ${y.toFixed(2)}`).join(' ')

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 ${SIZE} ${SIZE}">
  <!--
    Generated by scripts/build-tray-icon.mjs — edit the geometry there, not here.

    Reduced to the heptagon and wheel on purpose: this renders at 18x18 in the menu bar, where
    the full app icon's terminal badge and gradients turn to mush. Pure black on transparent is
    what macOS template images require; the system applies the colour.
  -->
  <g fill="none" stroke="#000" stroke-width="${STROKE}" stroke-linejoin="round" stroke-linecap="round">
    <path d="${path} Z"/>
    <circle cx="${CX}" cy="${CY}" r="${R_RIM}"/>
${spokes
  .map(
    ([[x1, y1], [x2, y2]]) =>
      `    <line x1="${x1.toFixed(2)}" y1="${y1.toFixed(2)}" x2="${x2.toFixed(2)}" y2="${y2.toFixed(2)}"/>`
  )
  .join('\n')}
  </g>
  <circle cx="${CX}" cy="${CY}" r="${R_HUB}" fill="#000"/>
</svg>
`

// ---------------------------------------------------------------- rasteriser

/** Shortest distance from p to segment ab. */
function distToSegment(px, py, [ax, ay], [bx, by]) {
  const dx = bx - ax
  const dy = by - ay
  const lenSq = dx * dx + dy * dy
  const t = lenSq === 0 ? 0 : Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / lenSq))
  return Math.hypot(px - (ax + t * dx), py - (ay + t * dy))
}

/** True when the design-space point falls on any inked shape. */
function isInk(x, y) {
  const half = STROKE / 2
  for (const [a, b] of [...edges, ...spokes]) {
    if (distToSegment(x, y, a, b) <= half) return true
  }
  // Stroked rim: near the circumference, not inside the disc.
  if (Math.abs(Math.hypot(x - CX, y - CY) - R_RIM) <= half) return true
  return Math.hypot(x - CX, y - CY) <= R_HUB
}

/**
 * Renders to RGBA. Alpha carries the shape (that is what the menu bar tints); RGB stays black.
 * 4x4 supersampling is enough to keep 1.25pt strokes smooth at 18px.
 */
function rasterise(pixels) {
  const scale = pixels / SIZE
  const SS = 4
  const data = Buffer.alloc(pixels * pixels * 4)

  for (let py = 0; py < pixels; py++) {
    for (let px = 0; px < pixels; px++) {
      let hits = 0
      for (let sy = 0; sy < SS; sy++) {
        for (let sx = 0; sx < SS; sx++) {
          const x = (px + (sx + 0.5) / SS) / scale
          const y = (py + (sy + 0.5) / SS) / scale
          if (isInk(x, y)) hits++
        }
      }
      const i = (py * pixels + px) * 4
      data[i] = data[i + 1] = data[i + 2] = 0
      data[i + 3] = Math.round((hits / (SS * SS)) * 255)
    }
  }
  return data
}

// ---------------------------------------------------------------- png encoder

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
  return c >>> 0
})

function crc32(buf) {
  let c = 0xffffffff
  for (const byte of buf) c = CRC_TABLE[(c ^ byte) & 0xff] ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}

function chunk(type, body) {
  const len = Buffer.alloc(4)
  len.writeUInt32BE(body.length)
  const typed = Buffer.concat([Buffer.from(type, 'ascii'), body])
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(typed))
  return Buffer.concat([len, typed, crc])
}

function encodePng(rgba, size) {
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(size, 0)
  ihdr.writeUInt32BE(size, 4)
  ihdr[8] = 8 // bit depth
  ihdr[9] = 6 // colour type: RGBA
  // 10-12: deflate / adaptive filtering / no interlace, all zero.

  // Each scanline is prefixed with its filter byte; 0 (None) keeps the encoder trivial and
  // costs nothing at this size.
  const raw = Buffer.alloc((size * 4 + 1) * size)
  for (let y = 0; y < size; y++) {
    raw[y * (size * 4 + 1)] = 0
    rgba.copy(raw, y * (size * 4 + 1) + 1, y * size * 4, (y + 1) * size * 4)
  }

  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0))
  ])
}

// ---------------------------------------------------------------- write

writeFileSync(join(root, 'resources/trayTemplate.svg'), svg)
console.log('resources/trayTemplate.svg')

for (const px of [18, 36]) {
  const name = px === 18 ? 'trayTemplate.png' : 'trayTemplate@2x.png'
  const png = encodePng(rasterise(px), px)
  writeFileSync(join(root, 'resources', name), png)
  console.log(`resources/${name} — ${px}x${px}, ${png.length} bytes`)
}
